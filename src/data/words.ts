import { LETTERS } from './letters'

export interface Word {
  ar: string
  tr: string
  zh: string
}

export interface Chapter {
  id: string
  title: string
  titleAr: string
  icon: string
  words: Word[]
}

type Row = [ar: string, tr: string, zh: string]
const ch = (id: string, title: string, titleAr: string, icon: string, rows: Row[]): Chapter => ({
  id,
  title,
  titleAr,
  icon,
  words: rows.map(([ar, tr, zh]) => ({ ar, tr, zh })),
})

