import type { Word } from './words'

export interface WordToken {
  ar: string
  tr: string
  zh: string
  role: string
  note?: string
}

export interface LessonSentence {
  ar: string
  tr: string
  zh: string
  tokens: WordToken[]
}

export interface GrammarPoint {
  title: string
  formula?: string
  desc: string
  examples: { ar: string; tr: string; zh: string; highlight?: string }[]
}

export interface CourseLesson {
  id: string
  stage: number
  stageTitle: string
  number: string
  title: string
  titleAr: string
  subtitle: string
  icon: string
  points: GrammarPoint[]
  vocab: Word[]
  sentences: LessonSentence[]
}

const tok = (ar: string, tr: string, zh: string, role: string, note?: string): WordToken => ({
  ar,
  tr,
  zh,
  role,
  note,
})

/** Infer grammatical case from the token's own role, not other words mentioned in its explanation. */
export function caseTypeForToken(t: WordToken): 'nom' | 'acc' | 'gen' | null {
  const s = t.role
  if (/主格/.test(s)) return 'nom'
  if (/宾格/.test(s)) return 'acc'
  if (/属格/.test(s)) return 'gen'
  if (/宾格|宾语|副词|مَنْصُوب|مَفْعُول|ظَرْف|اسْم إِنَّ|خَبَر كَانَ/.test(s)) return 'acc'
  if (/属格|偏次|受词|مَجْرُور|مُضَاف إِلَيْهِ/.test(s)) return 'gen'
  if (/主格|起词|述语|主语|مَرْفُوع|مُبْتَدَأ|خَبَر|فَاعِل|اسْم كَانَ/.test(s)) return 'nom'
  return null
}

